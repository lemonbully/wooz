# OneWooz HA re-architecture — Phase 1: security groups, ElastiCache, ALB, NLB.
# Run in PowerShell. Captures all ARNs/endpoints into state.env for later phases.
# Safe to read top-to-bottom; each step prints what it created.

$ErrorActionPreference = "Stop"
$env:AWS_PAGER = ""
$R    = "ap-south-1"
$VPC  = "vpc-0bd5e11c18476714b"
$SUBA = "subnet-062eebb731d2e29a9"   # ap-south-1a, IGW-routed
$SUBB = "subnet-0d140ce3df79d0163"   # ap-south-1b, IGW-routed
$CERT = "arn:aws:acm:ap-south-1:521831014282:certificate/8d294ec5-2923-4010-9ca4-ec6fb68beae2"
$RDS_SG = "sg-0e754c8eee6428c2b"     # onewooz-rds
$state = "$PSScriptRoot\state.env"
"# generated by 01-edge-data.ps1" | Out-File -Encoding ascii $state
function Save($k,$v){ "$k=$v" | Add-Content -Encoding ascii $state; Write-Host "  $k = $v" }

Write-Host "== Security groups =="
$albSg = aws ec2 create-security-group --region $R --group-name onewooz-alb --description "OneWooz ALB" --vpc-id $VPC --query GroupId --output text
aws ec2 authorize-security-group-ingress --region $R --group-id $albSg --protocol tcp --port 80  --cidr 0.0.0.0/0 | Out-Null
aws ec2 authorize-security-group-ingress --region $R --group-id $albSg --protocol tcp --port 443 --cidr 0.0.0.0/0 | Out-Null
Save "ALB_SG" $albSg

$caddySg = aws ec2 create-security-group --region $R --group-name onewooz-caddy-task --description "OneWooz Caddy tasks (awsvpc)" --vpc-id $VPC --query GroupId --output text
aws ec2 authorize-security-group-ingress --region $R --group-id $caddySg --protocol tcp --port 80  --cidr 0.0.0.0/0 | Out-Null
aws ec2 authorize-security-group-ingress --region $R --group-id $caddySg --protocol tcp --port 443 --cidr 0.0.0.0/0 | Out-Null
Save "CADDY_SG" $caddySg

$instSg = aws ec2 create-security-group --region $R --group-name onewooz-ecs-instance --description "OneWooz ECS EC2 instances" --vpc-id $VPC --query GroupId --output text
# ALB -> web on ECS dynamic host ports
aws ec2 authorize-security-group-ingress --region $R --group-id $instSg --protocol tcp --port 32768-65535 --source-group $albSg | Out-Null
Save "INSTANCE_SG" $instSg

# Caddy -> ALB internal :8080 upstream
aws ec2 authorize-security-group-ingress --region $R --group-id $albSg --protocol tcp --port 8080 --source-group $caddySg | Out-Null

$redisSg = aws ec2 create-security-group --region $R --group-name onewooz-cache --description "OneWooz ElastiCache" --vpc-id $VPC --query GroupId --output text
aws ec2 authorize-security-group-ingress --region $R --group-id $redisSg --protocol tcp --port 6379 --source-group $instSg  | Out-Null
aws ec2 authorize-security-group-ingress --region $R --group-id $redisSg --protocol tcp --port 6379 --source-group $caddySg | Out-Null
Save "REDIS_SG" $redisSg

# RDS: allow the new ECS instances to reach MySQL
aws ec2 authorize-security-group-ingress --region $R --group-id $RDS_SG --protocol tcp --port 3306 --source-group $instSg | Out-Null
Write-Host "  RDS SG now allows 3306 from ECS instances"

Write-Host "== ElastiCache (redis, cache.t4g.micro) =="
aws elasticache create-cache-subnet-group --region $R --cache-subnet-group-name onewooz-cache --cache-subnet-group-description "OneWooz" --subnet-ids $SUBA $SUBB | Out-Null
aws elasticache create-cache-cluster --region $R --cache-cluster-id onewooz-redis --engine redis --cache-node-type cache.t4g.micro --num-cache-nodes 1 --cache-subnet-group-name onewooz-cache --security-group-ids $redisSg | Out-Null
Write-Host "  ElastiCache creating (endpoint resolved in Phase 3)..."

Write-Host "== Application Load Balancer (platform hosts, ACM) =="
$alb = aws elbv2 create-load-balancer --region $R --name onewooz-alb --type application --scheme internet-facing --subnets $SUBA $SUBB --security-groups $albSg --query "LoadBalancers[0].LoadBalancerArn" --output text
$albDns = aws elbv2 describe-load-balancers --region $R --load-balancer-arns $alb --query "LoadBalancers[0].DNSName" --output text
$albZone = aws elbv2 describe-load-balancers --region $R --load-balancer-arns $alb --query "LoadBalancers[0].CanonicalHostedZoneId" --output text
Save "ALB_ARN" $alb; Save "ALB_DNS" $albDns; Save "ALB_ZONE" $albZone

$webTg = aws elbv2 create-target-group --region $R --name onewooz-web --protocol HTTP --port 8000 --vpc-id $VPC --target-type instance --health-check-path /health/live --health-check-interval-seconds 15 --healthy-threshold-count 2 --unhealthy-threshold-count 3 --matcher HttpCode=200 --query "TargetGroups[0].TargetGroupArn" --output text
Save "WEB_TG" $webTg

# 443 (ACM) -> web ; 80 -> redirect to 443 ; 8080 internal -> web (Caddy upstream)
aws elbv2 create-listener --region $R --load-balancer-arn $alb --protocol HTTPS --port 443 --certificates CertificateArn=$CERT --ssl-policy ELBSecurityPolicy-TLS13-1-2-2021-06 --default-actions Type=forward,TargetGroupArn=$webTg | Out-Null
aws elbv2 create-listener --region $R --load-balancer-arn $alb --protocol HTTP --port 80 --default-actions "Type=redirect,RedirectConfig={Protocol=HTTPS,Port=443,StatusCode=HTTP_301}" | Out-Null
aws elbv2 create-listener --region $R --load-balancer-arn $alb --protocol HTTP --port 8080 --default-actions Type=forward,TargetGroupArn=$webTg | Out-Null
Write-Host "  ALB listeners 443/80/8080 created"

Write-Host "== Network Load Balancer (onewooz.site + custom domains -> Caddy) =="
$nlb = aws elbv2 create-load-balancer --region $R --name onewooz-nlb --type network --scheme internet-facing --subnets $SUBA $SUBB --query "LoadBalancers[0].LoadBalancerArn" --output text
$nlbDns = aws elbv2 describe-load-balancers --region $R --load-balancer-arns $nlb --query "LoadBalancers[0].DNSName" --output text
$nlbZone = aws elbv2 describe-load-balancers --region $R --load-balancer-arns $nlb --query "LoadBalancers[0].CanonicalHostedZoneId" --output text
Save "NLB_ARN" $nlb; Save "NLB_DNS" $nlbDns; Save "NLB_ZONE" $nlbZone

$caddyTg443 = aws elbv2 create-target-group --region $R --name onewooz-caddy-443 --protocol TCP --port 443 --vpc-id $VPC --target-type ip --health-check-protocol TCP --query "TargetGroups[0].TargetGroupArn" --output text
$caddyTg80  = aws elbv2 create-target-group --region $R --name onewooz-caddy-80  --protocol TCP --port 80  --vpc-id $VPC --target-type ip --health-check-protocol TCP --query "TargetGroups[0].TargetGroupArn" --output text
Save "CADDY_TG443" $caddyTg443; Save "CADDY_TG80" $caddyTg80
aws elbv2 create-listener --region $R --load-balancer-arn $nlb --protocol TCP --port 443 --default-actions Type=forward,TargetGroupArn=$caddyTg443 | Out-Null
aws elbv2 create-listener --region $R --load-balancer-arn $nlb --protocol TCP --port 80  --default-actions Type=forward,TargetGroupArn=$caddyTg80  | Out-Null
Write-Host "  NLB listeners 443/80 created"

Write-Host ""
Write-Host "Phase 1 complete. State saved to $state"
Write-Host "ALB DNS: $albDns"
Write-Host "NLB DNS: $nlbDns"
